/* Карточки-счётчики над таблицами. Возвращают строки: куда их положить,
   знает корень страницы, а не они. Какое из трёх положений сейчас у
   признака, плашка тоже не решает — это расставляет корень по готовым
   узлам, потому что разметка карточек пересобирается только со сменой
   данных, а фильтр меняется куда чаще. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory(require('./text.js'), require('./labels.js'));
  } else {
    root.KP = root.KP || {};
    root.KP.cards = factory(root.KP.text, root.KP.labels);
  }
}(typeof globalThis !== 'undefined' ? globalThis : this,
  function (text, labels) {
  'use strict';

  const esc = text.esc, plural = text.plural;

  function cardHtml(filter, big, number, unit, sub, label, tip, labelCls) {
    const cls = `card${big ? ' big' : ''}${filter ? ' clickable' : ''}`;
    const open = filter
      ? `<button type="button" class="${cls}" data-filter="${esc(filter)}"`
        + ' aria-pressed="false"'
      : `<div class="${cls}"`;
    /* У большой карточки подпись стоит над числом, у мелкой — под ним:
       большие читают сверху вниз как заголовки, мелкие — как ряд значков. */
    const title = `<div class="l${labelCls ? ` ${labelCls}` : ''}">`
      + `${esc(label)}</div>`;
    return `${open} data-tip="${esc(tip)}">`
      + (big ? title : '')
      + `<div class="n">${esc(number)}`
      + (unit ? ` <span class="unit">${esc(unit)}</span>` : '') + '</div>'
      + `<div class="rpm">${esc(sub || '')}</div>`
      + (big ? '' : title)
      + (filter ? '</button>' : '</div>');
  }

  /* Группа сводки: числа внутри неё отвечают на один вопрос и стоят на
     одной плоскости. Плоскость и есть всё, чем группа отделена от соседних,
     — ни линии, ни подписи над ней нет: подписывать нечего, каждое число
     названо само, а второе имя над ними повторяло бы их.

     Долю ширины задаёт css по этим же именам: сколько кому места, решает
     раскладка, а не скрипт. */
  function group(kind, inner) {
    return `<div class="cgroup${kind ? ' ' + kind : ''}">${inner}</div>`;
  }

  /* Карточки вкладки «Состояние»: большие — про весь тег, мелкие — про
     классы патчей. Возвращаем обе строки сразу: считаются они по одному
     снапшоту, а кладут их в два разных узла. */
  function stateCards(snap) {
    if (!snap) return { big: '', classes: '' };
    const c = snap.counts;
    let rpms = 0;
    for (const b of snap.builds) rpms += b.rpms.length;

    /* Три группы: что за билды в теге, что у них в каталоге патчей и как
       прошёл сбор. Наследование стоит рядом с числом тега, а не с патчами:
       и то, и другое — про состав тега, про сами билды, а патчи — уже про
       их содержимое. */
    const big =
      group('lead',
        cardHtml('all', true, c.builds, plural(c.builds, 'билд', 'билда', 'билдов'),
          `${rpms} RPM`, 'в теге',
          `Все последние билды тега ${snap.tag} и собранные из них бинарные `
          + 'пакеты. Клик снимает все фильтры.')
      + cardHtml('inherited', true, c.inherited,
          plural(c.inherited, 'билд', 'билда', 'билдов'),
          `${c.direct} затегованы прямо`, 'унаследованы',
          `Билды, которые висят не в теге ${snap.tag}, а в одном из его `
          + 'родителей, и попали сюда наследованием. В колонке «тег» видно, '
          + 'из какого именно. Клик оставит в таблице только их.'))
      + group('one',
        cardHtml('has-patch', true, c.with_patches,
          plural(c.with_patches, 'билд', 'билда', 'билдов'),
          `${c.patch_files} `
          + `${plural(c.patch_files, 'файл', 'файла', 'файлов')} патчей`,
          'с патчами',
          'Билды, у которых в каталоге PATCH ветки лежит хотя бы один файл. '
          + 'Клик оставит в таблице только их.'))
      /* Сбор — не про сам тег, а про то, что мы о нём знаем: у этих трёх
         чисел свой предмет, поэтому и своя плоскость.

         Каждое считает билды, у которых есть запись его уровня, и билд с
         ошибкой и заметкой разом стоит в двух карточках сразу. Сумма трёх
         чисел из-за этого бывает больше числа билдов: они отвечают «у
         скольких билдов такая запись», а не делят тег на три части. */
      + group('health',
        cardHtml('problem', true, c.problems,
          plural(c.problems, 'билд', 'билда', 'билдов'),
          `${c.without_patches} без каталога PATCH`, 'с проблемами',
          'Билды, у которых при сборе данных случилась ошибка: нет исходника, '
          + 'GitLab ответил отказом, ветка исчезла. Данных по такому билду не '
          + 'хватает, и это видно в его строке. Клик оставит только их.')
      /* Билды, где сбор состоялся, но с оговоркой. Своя карточка, а не
         строка в подсказке чужой: искать их приходится ровно так же — по
         одному признаку, кликом, — а мешать их с ошибками значит потерять
         и те, и другие. */
      + cardHtml('warning', true, c.warnings,
          plural(c.warnings, 'билд', 'билда', 'билдов'),
          'сбор с оговоркой', 'с предупреждениями',
          'Билды, по которым данные собраны, но отвечают на слегка другой '
          + 'вопрос: патчи сняты не с того коммита, из которого билд собран, '
          + 'дерево прочитано на подменённом хосте. Если у билда есть и '
          + 'ошибка, он стоит и в соседней карточке. Клик оставит только их.')
      /* Третий уровень записей сбора. Своя карточка по той же причине, что
         и у предупреждений: заметки ищут так же, кликом, а смешанные с
         остальными они перестали бы отличаться от беды. */
      + cardHtml('note', true, c.notes,
          plural(c.notes, 'билд', 'билда', 'билдов'),
          'записано к сведению', 'с заметками',
          'Билды, по которым сбор записал что-то к сведению: например, '
          + 'сравнивать было нечего — у билда нет коммита или ветки. Строку '
          + 'такая запись не красит, и на соседние карточки не влияет: билд '
          + 'с ошибкой и заметкой стоит и там, и тут. Клик оставит только их.'));

    const classes = labels.classOrder(c.by_class).map((name) => {
      const b = c.by_class[name];
      return cardHtml(text.slug(name), false, b.builds,
        plural(b.builds, 'билд', 'билда', 'билдов'),
        `${b.files} ${plural(b.files, 'файл', 'файла', 'файлов')}`,
        name, `Билды, где есть хотя бы один патч класса ${name}, и сколько `
        + 'таких файлов всего. Клик оставит в таблице только их.',
        labels.classCls(name));
    }).join('');
    return { big, classes };
  }

  /* Движение знаками: пришло, ушло, переписано. Ноль не пишем — три слота
     из нулей читаются как данные, а не сообщают ничего; когда не двигалось
     ничего, остаётся прочерк. Ровно то же и теми же знаками говорит
     markup.delta в колонках «Δ патчей» и «Δ RPM» — но она рисует цветные
     span'ы, и её разметка приколочена тестом на неизменность. Общей функции
     из них двоих не выходит; знаки же обязаны совпадать, иначе карточка и
     колонка под ней рассказывали бы об одном разными словами. */
  function signs(added, removed, rewritten) {
    const out = [];
    if (added) out.push(`+${added}`);
    if (removed) out.push(`−${removed}`);
    if (rewritten) out.push(`~${rewritten}`);
    return out.length ? out.join(' ') : '—';
  }

  function sumOf(rows, field) {
    let n = 0;
    for (const row of rows) n += row[field].length;
    return n;
  }

  /* Итоги перехода: сколько билдов было в теге, сколько стало, на сколько
     их стало больше, сколько времени между сборами и сколько файлов за это
     время сдвинулось. Крупно и первым рядом, как итоги тега на
     «Состоянии»: разрезы под ними про то, у скольких компонентов что
     изменилось, а этот ряд — про то, между чем считали и насколько.

     Шесть карточек на три плоскости — столько же и так же, как на
     «Состоянии»: вкладки открывают одну за другой, и ряд, который при
     переключении меняет счёт, читался бы как другая страница. Ряд из двух
     карточек в ширину полосы не ложится ничем — либо узкие плашки и
     пустота справа, либо два числа, растянутые в плакат.

     Числа сторон берутся у снапшотов, а не по строкам таблицы: строка — это
     компонент перехода, и компонент, которого на этой стороне ещё (или уже)
     нет, в ней всё равно стоит.

     Под числом стороны — тег и время сбора. Тега мало: два прогона одного
     тега — законный случай, и «было os-9.4 → стало os-9.4» без времени
     сбора не сказало бы, какой из них какой. */
  function pairCards(pair, from, to) {
    if (!pair || !from || !to) return '';
    const was = from.counts.builds, now = to.counts.builds;
    const delta = now - was;
    const size = Math.abs(delta);
    const gap = text.gapLabel(from.generated, to.generated).split(' ');
    /* Движение файлов считаем по строкам, а не по счётчикам пары: счётчики
       сверяются с питоновским эталоном, который таких чисел не знает, и
       дописывать их туда ради двух подписей значило бы править эталон
       руками — а он сторож того, что страница считает ровно как питон.

       Строки те же самые, что стоят в таблице, поэтому число карточки —
       это в точности сумма колонки под ней. Из чего следует и то, чего
       карточка не считает: у компонента, который появился или исчез
       целиком, сравнивать нечего, в колонке у него прочерк, и файлы,
       которые он принёс с собой или унёс, в движение не идут. Сколько
       таких компонентов, говорит соседняя карточка «разница». */
    const rows = pair.rows;
    const pAdd = sumOf(rows, 'patches_added');
    const pDel = sumOf(rows, 'patches_removed');
    const pMod = sumOf(rows, 'patches_rewritten');
    const rAdd = sumOf(rows, 'rpms_added');
    const rDel = sumOf(rows, 'rpms_removed');

    function side(snap, count, label, tip) {
      return cardHtml(null, true, count,
        plural(count, 'билд', 'билда', 'билдов'),
        `${snap.tag}, ${text.stampOf(snap.generated)}`, label, tip);
    }

    /* Стороны — предмет перехода; разница со сроком и движение файлов —
       про него же, но во вторую очередь. Групп столько же, сколько на
       «Состоянии», и разложены они так же: вкладки открывают одну за
       другой, и ряд, который при переключении перестраивается, читался бы
       как другая страница. */
    return group('major',
        side(from, was, 'было',
          'Сколько билдов было в теге на начало перехода — все последние '
          + `билды ${from.tag} на момент того сбора.`)
        + side(to, now, 'стало',
          `Сколько билдов в теге на конец перехода — все последние билды `
          + `${to.tag} на момент того сбора.`))
      + group('scale',
        cardHtml(null, true,
          (delta > 0 ? '+' : delta < 0 ? '−' : '') + size,
          plural(size, 'билд', 'билда', 'билдов'),
          `появилось ${pair.counts.added}, исчезло ${pair.counts.removed}`,
          'разница',
          'На сколько билдов в теге стало больше или меньше. Ноль здесь не '
          + 'значит «ничего не менялось»: сколько компонентов ушло, столько '
          + 'могло и прийти, — про это соседние карточки.')
        /* Срок берём тот же, что подписывает отрезок рельса: одна мера в
           двух местах, и читаются они как одно. Пустой он бывает у сборов,
           между которыми меньше минуты, и у непрочитанного времени. */
        + cardHtml(null, true, gap[0] || '—', gap[1] || '',
          'между сборами снапшотов', 'срок',
          'Сколько времени прошло между двумя сборами снапшотов. Это не срок '
          + 'жизни тега: снапшот снимают когда придётся, и всё, что случилось '
          + 'с тегом внутри этого срока, дашборд видит только концами.'))
      /* Третья плоскость — про содержимое билдов, а не про их число: она
         отвечает на тот же вопрос, что и «с патчами» на «Состоянии», но у
         перехода этот вопрос звучит как «сколько сдвинулось». Своя
         плоскость, а не приписка к сторонам: под числом стороны стоят тег
         и время сбора, и место там занято тем, без чего сторону не
         назвать. */
      + group('moved',
        cardHtml(null, true, pAdd + pDel + pMod,
          plural(pAdd + pDel + pMod, 'файл', 'файла', 'файлов'),
          signs(pAdd, pDel, pMod), 'патчи',
          'Сколько файлов патчей пришло, ушло и переписано под тем же именем '
          + 'за весь переход. Это сумма колонки «Δ патчей»: компоненты, '
          + 'которые появились или исчезли целиком, сюда не идут — сравнивать '
          + 'их не с чем, и файлы, которые они принесли или унесли, здесь не '
          + 'посчитаны. Сколько их, говорит «разница».')
        + cardHtml(null, true, rAdd + rDel,
          plural(rAdd + rDel, 'пакет', 'пакета', 'пакетов'),
          signs(rAdd, rDel, 0), 'RPM',
          'Сколько бинарных пакетов пришло и ушло у компонентов, которые '
          + 'остались в теге. Это сумма колонки «Δ RPM»: компоненты, которые '
          + 'появились или исчезли целиком, сюда не идут — сравнивать их не с '
          + 'чем, и все их пакеты остались бы за скобками.'));
  }

  /* Разрезы разложены по вопросам, на которые отвечают: что стало с самим
     компонентом, что с его версией, что с патчами, что со сборкой. Списки
     объявлены здесь, рядом с самими разрезами: плоскость — это вопрос, а
     не порядковый номер, и новый разрез попадает в неё по смыслу, а не по
     месту в массиве.

     Четыре плоскости, а не две полосы во всю ширину: полоса из шести чисел
     растягивала каждое на шестую часть экрана, и ряд читался пустотой
     между подписями. По три числа плоскость встаёт вдвое у́же, и в ряд их
     ложится две. */
  const PLANES = [['changed', 'added', 'removed'],
                  ['upgraded', 'downgraded', 'unchanged'],
                  ['patches+', 'patches-', 'patches~'],
                  ['repackaged', 'branch-changed', 'tag-changed']];

  function diffCards(pair) {
    if (!pair) return '';
    const c = pair.counts;
    const spec = [
      ['changed', c.changed, 'изменились',
       'Компоненты, у которых изменилось хоть что-нибудь: версия, набор патчей, '
       + 'состав RPM или ветка.'],
      ['added', c.added, 'появились', 'Компонентов не было в старом теге.'],
      ['removed', c.removed, 'исчезли', 'Компонентов нет в новом теге.'],
      ['upgraded', c.upgraded, 'версия выросла',
       'Сравнение version-release по правилам rpm.'],
      ['downgraded', c.downgraded, 'версия упала',
       'Версия в новом теге ниже, чем в старом. Обычно это откат.'],
      ['unchanged', c.unchanged, 'версия та же',
       'Version-release совпал. Патчи и состав RPM при этом могли измениться.'],
      ['patches+', c.patches_added, 'патчи пришли',
       'В каталоге PATCH появились новые файлы.'],
      ['patches-', c.patches_removed, 'патчи ушли',
       'Из каталога PATCH исчезли файлы. Стоит проверить, не потеряно ли исправление.'],
      ['patches~', c.patches_rewritten, 'патчи переписаны',
       'Файл остался под тем же именем, а содержимое другое: сравнение идёт '
       + 'по blob sha. Снапшоты, собранные до 2.3.0, sha не несут — в паре '
       + 'с таким снапшотом число всегда ноль.'],
      ['repackaged', c.repackaged, 'состав RPM',
       'Компонент остался, но набор его бинарных пакетов изменился.'],
      ['branch-changed', c.branch_changed, 'сменили ветку',
       'Билд приехал из другой ветки GitLab, чем в старом теге.'],
      ['tag-changed', c.tag_changed, 'переехали между тегами',
       'Билд теперь висит в другом koji-теге: был унаследован — стал '
       + 'затегован прямо, или наоборот. Обычное наследование сюда не '
       + 'попадает: сравнивается сам тег билда, а не то, каким он выглядит '
       + 'из выбранного.']
    ];
    /* «3 из 105» само по себе не говорит, чего именно три: подпись под
       числом называет исход — «исчезли», — а не то, что считали. Считаем же
       мы компоненты перехода, и это не то же самое, что билды: у
       появившегося компонента билда нет в старом теге, у исчезнувшего — в
       новом, а строка в таблице всё равно одна.

       Слово встаёт своей строкой, а не приписывается к «из 105»: строка
       эта в мелкой карточке всё равно есть — под числом её держит пустой
       подзаголовок, — и там оно не переносится ни при какой ширине, тогда
       как «из 105 компонентов» одной строкой ломалось пополам, стоило
       плоскостям встать по две в ряд. Читается сверху вниз целой фразой:
       «103 из 105 / компонентов / изменились». */
    const total = pair.rows.length;
    const scale = plural(total, 'компонента', 'компонентов', 'компонентов');

    /* Порядок чисел прежний: границы плоскостей легли ровно там, где один
       вопрос и так сменялся другим, и переставлять ради них нечего. Разрез,
       не названный ни в одной плоскости, потерялся бы молча — поэтому
       собираем по спискам, а лишнее ловит тест на состав. */
    function plane(keys) {
      return group('cut', spec.filter(([key]) => keys.indexOf(key) !== -1)
        .map(([key, count, label, tip]) =>
          cardHtml(key, false, count, `из ${total}`, scale,
                   label, `${tip} Клик — фильтр.`)).join(''));
    }

    return PLANES.map(plane).join('');
  }

  return { stateCards, pairCards, diffCards };
}));
